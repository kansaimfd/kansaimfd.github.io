/**
 * 設備の有無。true＝あり / false＝なし。
 * **undefined は「なし」ではなく「未調査」**を意味する（YAMLではキーごと省略する）。
 * この3値の区別を潰さないこと。false と undefined を同一視すると、
 * 実際には設備がある施設が絞り込みから消える。
 */
export type Availability = boolean

/** 情報の出所。1レコードに複数持てる */
export interface Source {
  URL: string
  /** YYYY-MM-DD。この日にこのURLで内容を確認したという意味 */
  確認日: string
  /** このURLで裏が取れたフィールド名。省略時はレコード全体 */
  項目?: string[]
  /** 確認できなかった点・不確かな点 */
  備考?: string
}

/** 最寄りの交通機関の種別。→ Station.種別 */
export type StationKind = '駅' | 'バス停'

export interface Station {
  /**
   * 鉄道の駅かバス停か。**省略＝駅**。
   *
   * バス停を書くのは、鉄道駅から歩けない施設（守山市民ホールは守山駅から徒歩30分）が
   * あり、公式もバスで案内しているため。ただし「しづかホール前」のように名前からは
   * バス停と分からないものがあり、駅座標マスタとの照合が誤検出になっていた。
   * 名前が「◯◯バス停」で終わるものは書かなくてよい（そちらは名前から判別できる）。
   */
  種別?: StationKind
  /** 同一駅に複数路線が乗り入れる場合は並べる 例: [御堂筋線, 中央線] */
  路線?: string[]
  駅: string
  /** 出口・改札名 例: 23号出口, 南改札口 */
  出口?: string
  /** 徒歩分数。公式が距離のみ記載の場合はビルド時に補完される（駅徒歩推定 を参照） */
  駅徒歩?: number
  /** 道路距離（m）。直線距離ではない */
  駅距離?: number
  /** true なら 駅徒歩 は 駅距離 からビルド時に導出した推定値（80m/分・切り上げ） */
  駅徒歩推定?: boolean
}

/**
 * 貸館の休止・終了。**通常どおり貸せる施設ではキーごと省略する**。
 *
 * 既存の 休館日 は「毎週月曜」のような定休日を指すので、語がぶつからないよう
 * 「貸館」で束ねている。また 響都ホール のように**建物は開いているが貸館だけ終えた**
 * 施設があるため、「閉館」ではなく「貸館の状態」として持つ。
 */
export interface Rental {
  /**
   * - `休止` … 改修・災害などで一時的に貸していない。再開が予定されている
   * - `終了` … 貸館事業そのものを終えた。用途変更・閉館を含み、再開しない
   * - `予定` … **まだ借りられる**が、休止・終了が告知されている。`開始` が未来の月になる。
   *   ホールの予約は12か月前から取るので、利用者には今まさに必要な情報になる。
   *   時期が「令和11年度内」のようにしか決まっていない例があるため `開始` は必須にしない
   * - `廃止` … 施設そのものが無くなっている。建物の解体（葺合文化センター）のほか、
   *   **公式サイトが消え何年も活動の記録が無い**（堀江アルテ）ような運営実体の消滅も含む。
   *   `終了` と分けているのは、響都ホールのように**建物は開いていて貸館だけ終えた**、
   *   つまり施設としては現に在るものと区別するため。
   *   閉館の告知が無く状況証拠だけで判断した場合は、その旨を `理由` に必ず書くこと
   */
  状態: '休止' | '終了' | '予定' | '廃止'
  /** 休止・終了の始まり "YYYY-MM"。分かる場合のみ */
  開始?: string
  /** 再開予定 "YYYY-MM"。**休止のみ**。未定なら省略する */
  再開?: string
  /** 理由 例: 大規模改修工事, 貸館業務終了, 建て替えのため */
  理由?: string
}

/**
 * 「誰でも借りられるわけではない」施設の条件。**制約が無い施設ではキーごと省略する**。
 *
 * `貸館` は休止・終了を表すものなので、「今も貸しているが、借りられる人が限られる」を
 * 書く場所が無かった。借りられるかどうかは二値では表せない。
 *
 * - `公募選考` … 時間貸しをしておらず、公募・審査で利用者を選ぶ（京都芸術センター）
 * - `資格限定` … 利用者の資格が条例などで限られる（難波市民学習センターは生涯学習団体のみ）
 * - `要紹介` … 紹介者のある個人・団体に限る（フィガロホール）
 */
export type UsageConditionType = '公募選考' | '資格限定' | '要紹介'

export interface UsageCondition {
  種別: UsageConditionType
  /** 公式の記載に沿った説明。一覧では種別を、詳細ページではこの文を出す */
  説明: string
}

/** 施設に共通する属性（住所・アクセス・連絡先など、部屋によらないもの） */
export interface FacilityBase {
  ID: number
  施設名: string
  /**
   * 施設名のひらがな読み。五十音順ソートに使う。
   * 漢字を含む施設名には付ける（かな・カナのみの名前はビルド時に導出できるので不要）。
   * 括弧内の別名は読みに含めない。
   */
  施設名かな?: string
  都道府県: string
  /** 市・区・町・村まで。政令市は区まで、郡部は郡名から書く 例: 神戸市中央区, 佐用郡佐用町 */
  市区町村: string
  /** 町名・丁目・番地。半角数字とハイフンに統一する */
  番地以下: string
  /** ビル名・階・部屋番号。番地以下に混ぜるとジオコーディングの精度が落ちるため分ける */
  建物?: string
  TEL?: string
  /** "HH:MM" 24時間表記 */
  開館時間?: string
  閉館時間?: string
  休館日?: string
  URL?: string
  申込URL?: string
  料金URL?: string
  /** 台数 */
  駐車場?: number
  最寄駅?: Station[]
  /** 貸館を休止・終了している場合のみ。省略＝通常どおり貸している */
  貸館?: Rental
  /** 借りられる人が限られる場合のみ。省略＝制約なし */
  利用条件?: UsageCondition
  /**
   * 備品を**施設レベル**に持つのは、受付で申し込む貸出備品として扱われ、
   * どの部屋に置かれるかが公式に書かれていない施設があるため
   * （千里山コミュニティセンターは「ピアノ・譜面台は受付で申込（先着順）」とだけ書く）。
   * **置かれる部屋が決まっているなら部屋側に書く。**
   */
  ピアノ有無?: Availability
  譜面台貸出?: Availability
  譜面台数?: number
  経度: number
  緯度: number
  出典?: Source[]
  /** 出典[].確認日 の最新値。build-data.mjs が派生生成する（YAMLには書かない） */
  最終確認日?: string
}

/**
 * 地図に載せられる施設。コンサートホール（平坦化済み）と練習場の両方を受ける。
 * FacilityMap が使う分だけを FacilityBase から取り、独自に型を書き写さない
 * （書き写すとスキーマを直したときに片方だけ古いまま残る）。
 */
export type MappableFacility = Pick<
  FacilityBase,
  'ID' | '施設名' | '都道府県' | '市区町村' | '番地以下' | '建物' | '最寄駅' | '経度' | '緯度'
> & {
  /** 平坦化したコンサートホールだけが持つ */
  部屋名?: string
  /** 練習場一覧に並べた、コンサートホール併設の部屋だけが持つ */
  ホール併設?: true
}

export type PianoType = 'グランド' | 'アップライト' | '電子'

/**
 * ホール・練習室に共通する属性。備品は「有無(3値) ＋ 詳細(任意)」の形で持つ。
 *
 * 面積・定員をここに置いているのは、コンサートホール施設がスタジオや多目的室を
 * 併設しているのが普通だから（フェニーチェ堺は大ホール〜文化交流室まで10室ある）。
 */
interface RoomBase {
  部屋名?: string
  /** ㎡ */
  面積?: number
  /** 人 */
  定員?: number
  ピアノ有無?: Availability
  /** ピアノが複数種ある部屋は稀なため単一値で持つ */
  ピアノ種別?: PianoType
  ピアノメーカー?: string
  /**
   * 古楽・バロックの練習場所を探すときは、ピアノの有無と同じくらい効く条件になる。
   * **部屋名に「チェンバロ」とあっても実物は撤去されていることがある**ので
   * （Lesson Studio Poco四条）、根拠は本文の記載に取ること。
   */
  チェンバロ?: Availability
  譜面台貸出?: Availability
  /** 貸出本数。分かる場合のみ。「あるが本数不明」は 譜面台貸出 のみ true にする */
  譜面台数?: number
  /**
   * 楽器の可否。実際の施設で区別されているのはほぼ「打楽器」だけなので、
   * 金管・木管は分けずに 管楽器 でまとめる。細かい区別は 楽器制限 に書く。
   *
   * コンサートホール施設も音楽練習室を併設していることがあるので、部屋共通で持つ。
   */
  管楽器?: Availability
  打楽器?: Availability
  /**
   * 楽器についての条件・補足。「音量制限あり」「養生が必要」「木管のみ可」など。
   * **条件付きで使える場合は 管楽器/打楽器 を true にしたうえで、ここに条件を書く。**
   */
  楽器制限?: string
  /**
   * この部屋だけが休止・終了している場合に書く。施設側の 貸館 より優先される。
   *
   * 1施設の中で状態が分かれることは珍しくない。あましんアルカイックホールは
   * 大ホールが耐震工事で休止、中ホールは通常営業、小ホールは貸出終了、と3つに分かれる。
   * **施設側の 貸館 は「全室が対象」の意味**なので、一部の部屋だけなら必ずこちらに書く。
   */
  貸館?: Rental
}

/**
 * ホールの性格。上から順に当てはめて判定する。
 *
 * - `音楽専用` … 施設が自ら「音楽専用」「コンサート専用」と称している
 * - `小ホール・サロン` … 客席数がおおむね300席未満で、リサイタル・室内楽向け
 * - `多目的` … プロセニアム形式で緞帳・舞台機構を持ち、音楽以外（演劇・式典）にも使う。
 *   **音響反射板が可動式・設置式であることが実務上の目印**
 *
 * 判断がつかない場合は設定しない（未調査）。
 */
export type HallType = '音楽専用' | '多目的' | '小ホール・サロン'

/** コンサートホール施設内の個々のホール */
export interface Hall extends RoomBase {
  ホール種別?: HallType
  客席数?: number
  舞台幅?: number
  舞台奥行?: number
  パイプオルガン?: Availability
  /** 製作者。ストップ数などもここに書いてよい 例: クーン社（54ストップ） */
  オルガン製作者?: string
  /** 楽屋の合計収容人数。部屋数では実態を表せないため人数で持つ */
  楽屋収容人数?: number
  親子室?: Availability
}

/** concerthall.yaml の1レコード＝1施設 */
export interface ConcertHallFacility extends FacilityBase {
  築年月?: string
  部屋?: Hall[]
}

/**
 * 一覧・地図用にビルド時へ平坦化した「施設 × ホール」1件。
 * ID は施設IDなので、同一施設の複数ホールでは重複する。React key には キー を使うこと。
 *
 * **一覧で使うフィールドだけを挙げる。** 平坦化は施設の属性をホールの数だけ
 * 複製するので（88施設→284ホール）、一覧が読まないフィールドを載せると
 * 転送量が件数倍で膨らむ。TEL・休館日・料金URL・出典などはここに無い。
 * それらが要る詳細ページは、施設単位の ConcertHallFacility を使うこと。
 *
 * 実際に載せる値は transform.mjs の LIST_FACILITY_FIELDS / LIST_ROOM_FIELDS で
 * 決まる。**片方だけ足すと、型にはあるのに値が来ない**ので必ず両方を直す。
 */
export type ConcertHall = Pick<
  ConcertHallFacility,
  | 'ID'
  | '施設名'
  | '施設名かな'
  | '都道府県'
  | '市区町村'
  | '番地以下'
  | '建物'
  | '最寄駅'
  | 'URL'
  | '貸館'
  | '利用条件'
  | '駐車場'
  | '経度'
  | '緯度'
> &
  Pick<
    Hall,
    | '部屋名'
    | 'ホール種別'
    | '客席数'
    | '舞台幅'
    | '舞台奥行'
    | 'ピアノ有無'
    | 'パイプオルガン'
    | '譜面台貸出'
    | '親子室'
    /** 部屋ごとに休止・終了が分かれる施設があるので、施設側の値を上書きする */
    | '貸館'
  > & { キー: string }

export interface PracticeRoom extends RoomBase {
  部屋名: string
}

/** practice.yaml の1レコード＝1施設 */
export interface Practice extends FacilityBase {
  部屋?: PracticeRoom[]
}

/**
 * 一覧用に絞った練習場。
 *
 * 一覧と詳細ページで同じJSONを配っていたころ、練習場しか見ない利用者にも
 * 出典（施設あたり最大5KB）やTEL・休館日・申込URLまで全件ぶん届いていた。
 * 部屋も「最大の定員・面積」と「設備の3値」に畳んでしか読まないので、
 * 一覧が見る項目だけを残す。
 *
 * 実際に載せる値は transform.mjs の LIST_PRACTICE_FIELDS /
 * LIST_PRACTICE_ROOM_FIELDS で決まる。**片方だけ足すと型にはあるのに値が来ない。**
 */
export type PracticeListItem = Pick<
  Practice,
  | 'ID'
  | '施設名'
  | '施設名かな'
  | '都道府県'
  | '市区町村'
  | '番地以下'
  | '建物'
  | '最寄駅'
  | 'URL'
  | '貸館'
  | '利用条件'
  | '駐車場'
  | '経度'
  | '緯度'
  /** 施設レベルの貸出備品。部屋側と合わせて3値を出す */
  | 'ピアノ有無'
> & {
  部屋?: Pick<PracticeRoom, '定員' | '面積' | 'ピアノ有無' | '管楽器' | '打楽器' | 'チェンバロ'>[]
  /**
   * コンサートホール施設に併設された練習室・リハーサル室など（transform.mjs の
   * toHallPracticeList）。**詳細ページは /concert/:id** で、ID もコンサートホール側のもの。
   */
  ホール併設?: true
}
